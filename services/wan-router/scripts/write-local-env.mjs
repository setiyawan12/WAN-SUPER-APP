import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const routerRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const envPath = path.join(routerRoot, ".env.local");
const cliproxyHome = process.env.CLIPROXY_HOME
  || path.join(os.homedir(), ".wan-super-app", "cliproxyapi");
const keyPath = path.join(cliproxyHome, "renn-copilot-keys.json");

let proxyApiKey;
try {
  proxyApiKey = JSON.parse(fs.readFileSync(keyPath, "utf8")).proxyApiKey;
} catch {
  throw new Error(`CLIProxyAPI key file is unavailable: ${keyPath}`);
}
if (typeof proxyApiKey !== "string" || !proxyApiKey.trim()) {
  throw new Error(`CLIProxyAPI proxy key is missing: ${keyPath}`);
}

const values = {
  WAN_ENV: "dev",
  WAN_AUTH_MODE: "firebase",
  WAN_ENVELOPE_MODE: "local",
  WAN_LOCAL_ENVELOPE_KEY: "d2FuLXJvdXRlci1sb2NhbC1kZXYta2V5LTAwMDAwMDA=",
  WAN_FIREBASE_PROJECT_ID: "demo-wan-super-app",
  FIREBASE_AUTH_EMULATOR_HOST: "127.0.0.1:9099",
  WAN_DATABASE_URL: "postgres://wan_router:wan_router_dev@127.0.0.1:55432/wan_router",
  WAN_API_KEY_PEPPER: "wan-router-local-development-pepper-2026",
  WAN_CORS_ORIGINS: "http://127.0.0.1:5178",
  WAN_PROVIDER_MODE: "cliproxy",
  WAN_CLIPROXY_BASE_URL: "http://127.0.0.1:8317/v1",
  WAN_CLIPROXY_API_KEY: proxyApiKey.trim(),
};

const content = [
  "# Generated by npm run env:local:cliproxy. Do not commit.",
  ...Object.entries(values).map(([name, value]) => `${name}=${JSON.stringify(value)}`),
  "",
].join("\n");

const temporaryPath = `${envPath}.${process.pid}.tmp`;
fs.writeFileSync(temporaryPath, content, { encoding: "utf8", mode: 0o600 });
fs.renameSync(temporaryPath, envPath);
fs.chmodSync(envPath, 0o600);
console.log(`Wrote ${envPath} from ${keyPath}`);